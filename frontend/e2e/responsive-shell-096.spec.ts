test('shell keeps five shortcuts, one application menu and closes it before PIN management', async ({page})=>{
  await page.goto('/')
  const nav=page.getByRole('tablist',{name:'Chọn nội dung'})
  await expect(nav.getByRole('tab')).toHaveCount(5)
  const trigger=page.getByTestId('app-menu-open')
  await trigger.click()
  await expect(page.getByTestId('migarden-placeholder')).toBeVisible()
  await expect(page.getByTestId('migarden-placeholder')).toBeDisabled()
  await expect(nav.getByRole('tab',{name:'miGarden'})).toHaveCount(0)
  await page.getByTestId('private-pin-change-open').click()
  await expect(page.getByTestId('app-menu')).toBeHidden()
  await expect(page.getByRole('dialog',{name:'Đổi PIN',exact:true})).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})

test('Tracker regions retain a dirty capture and global navigation asks before losing it',async({page})=>{
  await page.route('**/api/notes?*',route=>route.fulfill({json:{items:[]}}))
  await page.goto('/')
  await page.getByRole('tab',{name:'Theo dõi'}).click()
  const card=page.locator('[data-testid="tracker-card"][data-tracker-id="019a0e2e-0000-7000-8003-000000000002"]')
  await card.getByTestId('tracker-button').click()
  await card.getByTestId('tracker-amount-input').fill('123000')
  await page.getByTestId('tracker-tab-report').click()
  await expect(page.getByTestId('tracker-region-report')).toBeVisible()
  await expect(page.getByTestId('tracker-region-capture')).toBeHidden()
  await page.getByTestId('tracker-tab-journal').click()
  await expect(page.getByTestId('tracker-entries-toggle')).toHaveAttribute('aria-expanded','true')
  await page.getByTestId('tracker-tab-manage').click()
  await expect(page.getByTestId('tracker-management')).toBeVisible()
  await page.getByTestId('tracker-tab-capture').click()
  await expect(card.getByTestId('tracker-amount-input')).toHaveValue('123000')
  await page.getByRole('tab',{name:'Ghi chú',exact:true}).click()
  await expect(page.getByTestId('leave-draft-confirm')).toBeVisible()
  await page.getByRole('button',{name:'Ở lại',exact:true}).click()
  await expect(card.getByTestId('tracker-amount-input')).toHaveValue('123000')
  await page.getByRole('tab',{name:'Ghi chú',exact:true}).click()
  await page.getByRole('button',{name:'Rời bản nháp',exact:true}).click()
  await expect(page.getByRole('tab',{name:'Ghi chú',exact:true})).toHaveAttribute('aria-selected','true')
})

test('domain navigation supports arrows and remains above the safe-area edge',async({page})=>{
  await page.route('**/api/notes?*',route=>route.fulfill({json:{items:[]}}))
  await page.goto('/')
  const tasks=page.getByRole('tab',{name:'Task',exact:true})
  await tasks.focus();await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab',{name:'Ghi chú',exact:true})).toBeFocused()
  await expect(page.getByRole('tab',{name:'Ghi chú',exact:true})).toHaveAttribute('aria-selected','true')
  const boxes=await page.getByRole('tablist',{name:'Chọn nội dung'}).getByRole('tab').evaluateAll(els=>els.map(el=>{const b=el.getBoundingClientRect();return{width:b.width,height:b.height,left:b.left,right:b.right,bottom:b.bottom}}))
  for(const b of boxes){expect(b.width).toBeGreaterThanOrEqual(44);expect(b.height).toBeGreaterThanOrEqual(44);expect(b.left).toBeGreaterThanOrEqual(0);expect(b.right).toBeLessThanOrEqual((page.viewportSize()?.width??0)+1);expect(b.bottom).toBeLessThanOrEqual((page.viewportSize()?.height??0)+1)}
})
